function ref(r: {
  id: string
  userId: string
  spotId: string
  title: string
  imageUrl: string
  tags: string[]
  shotAt?: string
  direction?: number
  focalLength?: number
  creatorTip?: string
  cameraMake?: string
  cameraModel?: string
  lensModel?: string
  aperture?: number
  iso?: number
  shutterSpeed?: string
  adjustment?: Reference['adjustment']
  likeCount: number
  commentCount: number
  createdAt: string
}): Reference {
  const creator = getUserById(r.userId)
  const spot = getSpotById(r.spotId)
  if (!creator || !spot) throw new Error(`mock reference ${r.id}: missing creator/spot`)

  return {
    id: r.id,
    userId: r.userId,
    spotId: r.spotId,
    title: r.title,
    imageUrl: r.imageUrl,
    creator,
    spot,
    tags: r.tags,
    shooting: {
      shotAt: r.shotAt,
      direction: r.direction,
      focalLength: r.focalLength,
      creatorTip: r.creatorTip,
    },
    exif: {
      cameraMake: r.cameraMake,
      cameraModel: r.cameraModel,
      lensModel: r.lensModel,
      focalLength: r.focalLength,
      aperture: r.aperture,
      iso: r.iso,
      shutterSpeed: r.shutterSpeed,
      shotAt: r.shotAt,
      latitude: spot.latitude,
      longitude: spot.longitude,
    },
    adjustment: r.adjustment,
    likeCount: r.likeCount,
    commentCount: r.commentCount,
    createdAt: r.createdAt,
  }
}

